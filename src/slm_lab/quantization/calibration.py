class CalibrationValidationError(ValueError):
    """Raised when the calibration corpus or its provenance is inconsistent."""


@dataclass
class PlainTensor:
    """A dependency-free stand-in for a runtime tensor.

    Carries just enough surface (``dtype`` and ``shape``) for
    :func:`slm_lab.contracts.static_cache.validate_tensor_mapping` while holding
    its payload as ordinary nested Python lists, so calibration inputs can be
    materialized and contract-checked without numpy, torch, or onnxruntime.
    """

    name: str
    dtype: str
    shape: tuple[int, ...]
    values: list[list[int]]


@dataclass(frozen=True)
class CalibrationSample:
    """One frozen calibration sequence and the reason it exists."""

    sample_id: str
    tier: str
    source_group: str
    source_fixture_id: str
    interface: str
    construction: str
    source_token_count: int
    tile_repeats: int
    truncated: bool
    context_length: int
    cache_capacity: int
    token_ids: tuple[int, ...]
    source_token_ids_sha256: str
    rationale: str

    @property
    def token_count(self) -> int:
        """Return the emitted token count, which equals the context length."""

        return len(self.token_ids)

    def as_record(self) -> dict[str, Any]:
        """Return the committed manifest row for this sample.

        The token IDs themselves are deliberately *not* committed: they are
        already committed once in the T10 bundle, and duplicating them would
        create a second place for them to drift. The SHA-256 pins them.

        ``distinct_token_ids`` is measured from the emitted sequence so that a
        reader can see how narrow each sample is without re-deriving it, and so
        that the qualitative ``rationale`` can never be read as a coverage
        measurement.
        """

        return {
            "id": self.sample_id,
            "tier": self.tier,
            "source_group": self.source_group,
            "source_fixture_id": self.source_fixture_id,
            "interface": self.interface,
            "construction": self.construction,
            "source_token_count": self.source_token_count,
            "tile_repeats": self.tile_repeats,
            "truncated": self.truncated,
            "context_length": self.context_length,
            "cache_capacity": self.cache_capacity,
            "token_count": self.token_count,
            "distinct_token_ids": len(set(self.token_ids)),
            "source_token_ids_sha256": self.source_token_ids_sha256,
            "token_ids_sha256": canonical_json_sha256(list(self.token_ids)),
            "rationale": self.rationale,
        }


def _load_json(path: Path) -> Any:
    """Read *path* as JSON, converting every read failure into a clean error.

    A corrupt or unreadable input is a validation failure like any other, so it
    must reach the CLI as a ``CalibrationValidationError`` and exit 1 with an
    ``error:`` line rather than as a raw decoder traceback. Mirrors
    ``slm_lab.quantization.parity._load_json``. ``UnicodeDecodeError`` is caught
    alongside ``JSONDecodeError`` because the handle decodes lazily inside
    ``json.load``, and it is a ``ValueError`` the CLI would not otherwise catch.
    """

    try:
        with path.open("r", encoding="utf-8") as handle:
            return json.load(handle)
    except OSError as exc:
        raise CalibrationValidationError(f"cannot read {path}: {exc}") from exc
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise CalibrationValidationError(f"cannot parse {path}: {exc}") from exc


def _load_yaml(path: Path) -> Any:
    """Read *path* as YAML with the same fail-closed contract as `_load_json`."""

    try:
        with path.open("r", encoding="utf-8") as handle:
            return yaml.safe_load(handle)
    except OSError as exc:
        raise CalibrationValidationError(f"cannot read {path}: {exc}") from exc
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise CalibrationValidationError(f"cannot parse {path}: {exc}") from exc


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise CalibrationValidationError(message)


def _tile_to_length(
    token_ids: Sequence[int],
    target_length: int,
    *,
    label: str,
) -> tuple[tuple[int, ...], int, bool]:
    """Repeat *token_ids* end to end and truncate to exactly *target_length*.

    Returns the emitted IDs, the number of whole source copies concatenated
    before truncation, and whether truncation actually discarded any token.
    """

    _require(len(token_ids) > 0, f"{label}: cannot tile an empty token sequence")
    _require(
        target_length > 0,
        f"{label}: target length must be positive, found {target_length}",
    )
    repeats = -(-target_length // len(token_ids))
    tiled = (list(token_ids) * repeats)[:target_length]
    truncated = repeats * len(token_ids) != target_length
    return tuple(tiled), repeats, truncated


def _rationale_for(fixture_id: str) -> str:
    try:
        return SELECTION_RATIONALE[fixture_id]
    except KeyError as exc:
        raise CalibrationValidationError(
            f"{fixture_id}: T10 fixture has no T40 selection rationale; "
            "a fixture may not enter the calibration corpus unattributed"
        ) from exc


def _validated_source_ids(
    record: Mapping[str, Any],
    *,
    vocab_size: int,
    label: str,
) -> tuple[int, ...]:
    token_ids = record.get("token_ids")
    _require(
        isinstance(token_ids, list) and len(token_ids) > 0,
        f"{label}: T10 record has no token IDs",
    )
    assert isinstance(token_ids, list)
    for token_id in token_ids:
        _require(
            isinstance(token_id, int) and not isinstance(token_id, bool),
            f"{label}: token IDs must be integers",
        )
        _require(
            0 <= token_id < vocab_size,
            f"{label}: token ID {token_id} outside model vocabulary [0, {vocab_size})",
        )
    _require(
        record.get("token_count") == len(token_ids),
        f"{label}: T10 token count drift",
    )
    _require(
        record.get("token_ids_sha256") == canonical_json_sha256(list(token_ids)),
        f"{label}: T10 token ID hash drift",
    )
    return tuple(token_ids)


def _ordered_source_records(
    bundle: Mapping[str, Any],
) -> list[tuple[str, Mapping[str, Any]]]:
    """Return T10 records in the declared, deterministic emission order."""

    for key in ("context_workloads", "raw_canaries", "chat_canary", "quality_subset"):
        _require(key in bundle, f"T10 bundle is missing {key!r}")

    contexts = sorted(
        bundle["context_workloads"],
        key=lambda record: int(record["context_length"]),
    )
    raw_canaries = sorted(bundle["raw_canaries"], key=lambda record: str(record["id"]))
    quality = sorted(bundle["quality_subset"], key=lambda record: str(record["id"]))

    ordered: list[tuple[str, Mapping[str, Any]]] = []
    ordered.extend(("context_workloads", record) for record in contexts)
    ordered.extend(("raw_canaries", record) for record in raw_canaries)
    ordered.append(("chat_canary", bundle["chat_canary"]))
    ordered.extend(("quality_subset", record) for record in quality)
    return ordered


def build_calibration_samples(
    bundle: Mapping[str, Any],
    model_contract: Mapping[str, Any],
) -> list[CalibrationSample]:
    """Derive every tier-1 calibration sample from the committed T10 bundle.

    Context workloads are used verbatim because their token counts already are
    frozen T12 prompt lengths. Every shorter fixture is tiled to the smallest
    frozen prompt length so that no emitted sequence ever needs padding.
    """

    vocab_size = int(model_contract["model"]["architecture"]["vocab_size"])
    _require(
        vocab_size == static_cache.VOCAB_SIZE,
        f"model contract vocabulary {vocab_size} differs from the T12 contract "
        f"value {static_cache.VOCAB_SIZE}",
    )

    samples: list[CalibrationSample] = []
    for index, (group, record) in enumerate(_ordered_source_records(bundle)):
        fixture_id = str(record["id"])
        label = f"{group}/{fixture_id}"
        source_ids = _validated_source_ids(
            record,
            vocab_size=vocab_size,
            label=label,
        )

        if group == "context_workloads":
            context_length = int(record["context_length"])
            _require(
                len(source_ids) == context_length,
                f"{label}: T10 context workload is not exactly {context_length} tokens",
            )
            token_ids, repeats, truncated = source_ids, 1, False
            construction = "verbatim"
        else:
            context_length = SHORT_FIXTURE_CONTEXT_LENGTH
            token_ids, repeats, truncated = _tile_to_length(
                source_ids,
                context_length,
                label=label,
            )
            construction = "tiled_then_truncated"

        _require(
            context_length in static_cache.CONTEXT_VARIANTS,
            f"{label}: context length {context_length} is not a frozen T12 "
            f"prompt length {tuple(static_cache.CONTEXT_VARIANTS)}",
        )
        samples.append(
            CalibrationSample(
                sample_id=f"cal-{index:02d}-{fixture_id}",
                tier=TIER_ONE_ID,
                source_group=group,
                source_fixture_id=fixture_id,
                interface=str(record["interface"]),
                construction=construction,
                source_token_count=len(source_ids),
                tile_repeats=repeats,
                truncated=truncated,
                context_length=context_length,
                cache_capacity=static_cache.CONTEXT_VARIANTS[context_length],
                token_ids=token_ids,
                source_token_ids_sha256=str(record["token_ids_sha256"]),
                rationale=_rationale_for(fixture_id),
            )
        )

    sample_ids = [sample.sample_id for sample in samples]
    _require(len(sample_ids) == len(set(sample_ids)), "calibration sample IDs collide")
    _require(
        sample_ids == sorted(sample_ids),
        "declared emission order is not ascending lexicographic by sample ID",
    )
    return samples


def build_prefill_tensors(sample: CalibrationSample) -> dict[str, PlainTensor]:
    """Materialize one sample as T12-conformant prefill input tensors.

    Every value is a plain Python ``int`` in a plain Python ``list``; nothing
    here needs numpy, torch, or onnxruntime. ``attention_mask`` is all ones by
    construction because the corpus never pads.
    """

    contract = static_cache.build_prefill_contract(sample.context_length)
    length = sample.token_count
    _require(
        length == sample.context_length,
        f"{sample.sample_id}: emitted {length} tokens for an "
        f"S{sample.context_length} prefill graph",
    )
    batch = static_cache.BATCH_SIZE
    tensors = {
        "input_ids": PlainTensor(
            name="input_ids",
            dtype=static_cache.TOKEN_DTYPE,
            shape=(batch, length),
            values=[list(sample.token_ids)],
        ),
        "attention_mask": PlainTensor(
            name="attention_mask",
            dtype=static_cache.MASK_DTYPE,
            shape=(batch, length),
            values=[[1] * length],
        ),
        "position_ids": PlainTensor(
            name="position_ids",
            dtype=static_cache.POSITION_DTYPE,
            shape=(batch, length),
            values=[list(range(length))],
        ),
    }
    static_cache.validate_tensor_mapping(tensors, contract.inputs)
    return tensors


def validate_prefill_tensors(sample: CalibrationSample) -> None:
    """Re-check one sample's emitted tensors against the frozen T12 contract.

    Be precise about what each half of this does.

    The mask and position assertions below are **construction post-conditions**,
    not independent checks. :func:`build_prefill_tensors` writes ``[1] * length``
    and ``list(range(length))`` a few lines earlier, so they can only fire if
    that function itself changes. "No sample is ever padded" is therefore
    guaranteed by *construction*; neither this function nor
    ``test_no_sample_is_ever_padded`` proves it about a tensor mapping this
    module did not build.

    The one genuinely independent failure this surfaces comes from
    :func:`build_prefill_tensors` itself: a token count that is not the graph's
    frozen prompt length, or a dtype or shape that
    :func:`slm_lab.contracts.static_cache.validate_tensor_mapping` rejects.
    """

    try:
        tensors = build_prefill_tensors(sample)
    except static_cache.CacheContractError as exc:
        raise CalibrationValidationError(
            f"{sample.sample_id}: prefill tensors violate the T12 contract: {exc}"
        ) from exc
    mask = tensors["attention_mask"].values[0]
    _require(
        all(value == 1 for value in mask),
        f"{sample.sample_id}: attention_mask contains a zero, which means the "
        "sample was padded; the T12 prefill contract forbids padding",
    )
    _require(
        tensors["position_ids"].values[0] == list(range(sample.token_count)),
        f"{sample.sample_id}: position_ids are not zero-based and contiguous",
    )


