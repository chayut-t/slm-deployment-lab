def build_coverage_measurements(
    samples: Sequence[CalibrationSample],
    *,
    vocab_size: int,
) -> dict[str, Any]:
    """Measure, rather than argue, how much of the input space the corpus sees.

    Every number here is computed from *samples* at generation time. The
    per-sample ``rationale`` strings are qualitative arguments about which token
    *classes* are present at which prefill shape; this block is the honest
    counterweight that keeps them from being read as coverage measurements.
    """

    distinct_overall: set[int] = set()
    per_group_ids: dict[str, set[int]] = {}
    per_group_tokens: dict[str, int] = {}
    for sample in samples:
        distinct_overall.update(sample.token_ids)
        per_group_ids.setdefault(sample.source_group, set()).update(sample.token_ids)
        per_group_tokens[sample.source_group] = (
            per_group_tokens.get(sample.source_group, 0) + sample.token_count
        )
    total_tokens = sum(per_group_tokens.values())

    contexts = sorted(
        (sample for sample in samples if sample.source_group == "context_workloads"),
        key=lambda sample: sample.context_length,
    )
    nested = all(
        longer.token_ids[: len(shorter.token_ids)] == shorter.token_ids
        for shorter, longer in zip(contexts, contexts[1:])
    )

    return {
        "measured_from": "the emitted tier-1 token IDs in this file",
        "distinct_token_ids": len(distinct_overall),
        "model_vocabulary_size": vocab_size,
        "vocabulary_fraction": round(len(distinct_overall) / vocab_size, 6),
        "distinct_token_ids_per_source_group": {
            group: len(ids) for group, ids in sorted(per_group_ids.items())
        },
        "token_share_per_source_group": {
            group: round(tokens / total_tokens, 4)
            for group, tokens in sorted(per_group_tokens.items())
        },
        "context_workloads_are_nested_prefixes": nested,
        "context_workload_chain": [f"S{sample.context_length}" for sample in contexts],
        "note": (
            "Read this block before reading any `rationale`. Two facts limit "
            "what the corpus can support. First, the four context workloads "
            "are token-ID prefixes of one another in ascending length order, "
            "because T10 built all four by repeating one authored seed; they "
            "are four *shape* arguments over one body of text, not four "
            "independent content arguments, and `token_share_per_source_group` "
            "shows how much of the token budget that one body of text "
            "consumes. Second, the corpus touches `distinct_token_ids` of the "
            f"{vocab_size} embedding rows in the model. No sample selection "
            "here should be read as covering the embedding table, the "
            "vocabulary, or any activation distribution; the only coverage "
            "argued is over deployment shapes and over the presence of a few "
            "named token classes. Widening it is tier-2 work owned by T41."
        ),
    }


def build_corpus(
    bundle: Mapping[str, Any],
    model_contract: Mapping[str, Any],
) -> dict[str, Any]:
    """Build the tier-1 corpus document whose canonical JSON is hashed.

    This mapping is exactly the payload behind
    ``calibration_corpus_canonical_json_sha256``. It contains everything that
    determines the calibration inputs - the source revision, the preprocessing
    contract, and the sample table - and nothing that does not, so a licence
    note or a prose edit elsewhere in the file never changes the corpus
    revision.
    """

    samples = build_calibration_samples(bundle, model_contract)
    vocab_size = int(model_contract["model"]["architecture"]["vocab_size"])
    per_context: dict[str, int] = {}
    per_group: dict[str, int] = {}
    for sample in samples:
        key = f"S{sample.context_length}"
        per_context[key] = per_context.get(key, 0) + sample.token_count
        per_group[sample.source_group] = (
            per_group.get(sample.source_group, 0) + sample.token_count
        )
    total_tokens = sum(sample.token_count for sample in samples)

    return {
        "schema_version": SCHEMA_VERSION,
        "task_id": TASK_ID,
        "corpus_id": CORPUS_ID,
        "corpus_version": CORPUS_VERSION,
        "tier": TIER_ONE_ID,
        "status": "required_and_committed",
        "license": TIER_ONE_LICENSE,
        "source_bundle": {
            "path": DEFAULT_TOKEN_BUNDLE.as_posix(),
            "canonical_json_sha256": canonical_json_sha256(bundle),
            "license": bundle["license"],
        },
        "preprocessing": build_preprocessing_contract(model_contract),
        "token_budget": {
            "sample_count": len(samples),
            "total_calibration_tokens": total_tokens,
            "tokens_per_prompt_shape": {
                f"S{length}": per_context[f"S{length}"]
                for length in sorted(static_cache.CONTEXT_VARIANTS)
                if f"S{length}" in per_context
            },
            "tokens_per_source_group": dict(sorted(per_group.items())),
            "note": (
                "Token budget is the number of token positions the range "
                "observers see, not a wall-clock cost. It is small on purpose: "
                "the corpus is a coverage argument over deployment shapes and "
                "token classes, not a statistical sample of natural text. "
                "Widening it is tier-2 work owned by T41."
            ),
        },
        "coverage": build_coverage_measurements(samples, vocab_size=vocab_size),
        "samples": [sample.as_record() for sample in samples],
    }


