"""Build and verify the frozen T40 post-training-quantization calibration corpus.

The corpus is deliberately derived from material this repository already
commits. Tier 1 (``t10_derived``) turns the CC0-1.0 T10 token fixtures into
prefill inputs that satisfy the frozen T12 static-cache contract, so the whole
corpus can be regenerated byte-for-byte on any machine with nothing installed
beyond the standard library and PyYAML. Tier 2 (``external_diversity``) only
*declares* revision-pinned public corpora as candidates for T41; no third-party
dataset row is ever committed here.

Nothing in this module quantizes anything. AIMET is Linux + CUDA only. What is
frozen here is the *input* half of a quantization experiment: which sequences
the range observers see, in which order, at which shapes, and under which
licence.
"""

