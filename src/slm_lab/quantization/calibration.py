def _validate_external_candidates(recorded: Mapping[str, Any]) -> None:
    _require(
        recorded.get("data_committed") is False,
        "tier-2 candidates must declare data_committed: false",
    )
    candidates = recorded.get("candidates")
    _require(
        isinstance(candidates, list) and len(candidates) > 0,
        "tier-2 candidate list is empty",
    )
    assert isinstance(candidates, list)
    for candidate in candidates:
        dataset_id = candidate.get("id", "<missing id>")
        _require(
            candidate.get("data_committed") is False,
            f"{dataset_id}: tier-2 dataset rows may not be committed",
        )
        revision = candidate.get("revision")
        _require(
            isinstance(revision, str)
            and len(revision) == 40
            and all(character in "0123456789abcdef" for character in revision),
            f"{dataset_id}: tier-2 revision must be a full 40-hex commit SHA",
        )
        licenses = candidate.get("license")
        _require(
            isinstance(licenses, list)
            and len(licenses) > 0
            and all(isinstance(name, str) and name.strip() for name in licenses),
            f"{dataset_id}: tier-2 licence must be a non-empty list of names",
        )
        _require(
            bool(str(candidate.get("license_obligations", "")).strip()),
            f"{dataset_id}: tier-2 licence obligations must be stated",
        )
    _require(
        recorded == build_external_candidates(),
        "tier-2 candidate table differs from the pinned, fetched values",
    )


def validate_documents(
    *,
    config: Mapping[str, Any],
    bundle: Mapping[str, Any],
    workload_config: Mapping[str, Any],
    model_contract: Mapping[str, Any],
    export_contract: Mapping[str, Any],
) -> None:
    """Validate the calibration contract against every committed input."""

    _require(
        config.get("schema_version") == SCHEMA_VERSION,
        "calibration contract: unsupported schema version",
    )
    _require(
        config.get("task_id") == TASK_ID,
        "calibration contract: unexpected task ID",
    )

    bundle_sha256 = canonical_json_sha256(bundle)
    expected_input_hashes = {
        DEFAULT_TOKEN_BUNDLE.as_posix(): bundle_sha256,
        DEFAULT_WORKLOAD_CONFIG.as_posix(): canonical_json_sha256(workload_config),
        DEFAULT_MODEL_CONTRACT.as_posix(): canonical_json_sha256(model_contract),
        DEFAULT_EXPORT_CONTRACT.as_posix(): canonical_json_sha256(export_contract),
    }
    recorded_inputs = config.get("inputs")
    _require(
        isinstance(recorded_inputs, list) and len(recorded_inputs) == 4,
        "calibration contract must record all four committed inputs",
    )
    assert isinstance(recorded_inputs, list)
    for entry in recorded_inputs:
        path = entry.get("path")
        _require(
            path in expected_input_hashes,
            f"calibration contract records an unknown input {path!r}",
        )
        _require(
            entry.get("canonical_json_sha256") == expected_input_hashes[path],
            f"{path}: recorded input hash drift",
        )

    corpus = config.get("calibration_corpus")
    _require(
        isinstance(corpus, Mapping),
        "calibration contract has no calibration_corpus block",
    )
    assert isinstance(corpus, Mapping)
    _require(
        corpus.get("source_bundle", {}).get("canonical_json_sha256") == bundle_sha256,
        "T10 token bundle hash drift: the frozen calibration source is not the "
        "bundle this repository commits",
    )

    expected_corpus = build_corpus(bundle, model_contract)
    _require(
        corpus.get("preprocessing") == expected_corpus["preprocessing"],
        "preprocessing contract drift",
    )
    _require(
        corpus.get("coverage") == expected_corpus["coverage"],
        "coverage measurement drift: the recorded coverage figures are not the "
        "ones measured from the emitted samples",
    )

    recorded_samples = corpus.get("samples")
    expected_samples = expected_corpus["samples"]
    _require(
        isinstance(recorded_samples, list),
        "calibration corpus has no sample table",
    )
    assert isinstance(recorded_samples, list)
    _require(
        len(recorded_samples) == len(expected_samples),
        f"calibration sample count drift: recorded {len(recorded_samples)}, "
        f"derived {len(expected_samples)}",
    )
    for recorded, expected in zip(recorded_samples, expected_samples, strict=True):
        label = recorded.get("id", "<missing id>")
        _require(
            recorded.get("id") == expected["id"],
            f"calibration sample ordering drift at {label!r}",
        )
        _require(
            recorded.get("token_count") == expected["token_count"],
            f"{label}: token count drift",
        )
        _require(
            recorded.get("context_length") == expected["context_length"],
            f"{label}: context assignment drift",
        )
        _require(
            recorded.get("token_ids_sha256") == expected["token_ids_sha256"],
            f"{label}: emitted token ID hash drift",
        )
        _require(
            recorded == expected,
            f"{label}: calibration sample record drift",
        )

    budget = corpus.get("token_budget", {})
    total = sum(int(sample["token_count"]) for sample in recorded_samples)
    _require(
        budget.get("total_calibration_tokens") == total,
        f"token budget drift: recorded "
        f"{budget.get('total_calibration_tokens')}, samples sum to {total}",
    )
    _require(
        budget.get("sample_count") == len(recorded_samples),
        "token budget sample count drift",
    )

    corpus_sha256 = canonical_json_sha256(corpus)
    _require(
        config.get("calibration_corpus_canonical_json_sha256") == corpus_sha256,
        "calibration corpus hash drift",
    )
    _require(
        corpus_sha256 == canonical_json_sha256(expected_corpus),
        "calibration corpus differs from the corpus derived from committed inputs",
    )
    expected_revision = calibration_dataset_revision(corpus_sha256)
    _require(
        config.get("calibration_dataset_revision") == expected_revision,
        f"calibration_dataset_revision drift: expected {expected_revision}",
    )
    _require(
        config.get("artifact_manifest_contract", {}).get("value") == expected_revision,
        "artifact manifest calibration_dataset_revision drift",
    )

    external = config.get("external_diversity_candidates")
    _require(
        isinstance(external, Mapping),
        "calibration contract has no tier-2 candidate block",
    )
    assert isinstance(external, Mapping)
    _validate_external_candidates(external)

    licensing = config.get("licensing", {})
    _require(
        licensing.get("repository_license") == REPOSITORY_LICENSE,
        "licensing: repository licence drift",
    )
    _require(
        licensing.get("tier_1_license") == TIER_ONE_LICENSE,
        "licensing: tier-1 licence drift",
    )
    _require(
        bundle.get("license") == TIER_ONE_LICENSE,
        "licensing: the T10 source bundle is no longer CC0-1.0",
    )
    _require(
        licensing.get("third_party_rows_committed") is False,
        "licensing: third-party dataset rows may not be committed",
    )

    for sample in build_calibration_samples(bundle, model_contract):
        validate_prefill_tensors(sample)

    expected_document = build_document(
        bundle=bundle,
        workload_config=workload_config,
        model_contract=model_contract,
        export_contract=export_contract,
    )
    _require(
        dict(config) == expected_document,
        "committed calibration contract differs from the derived contract",
    )


def load_inputs(repo_root: Path) -> dict[str, Any]:
    """Load every committed document the calibration contract depends on."""

    return {
        "bundle": _load_json(repo_root / DEFAULT_TOKEN_BUNDLE),
        "workload_config": _load_json(repo_root / DEFAULT_WORKLOAD_CONFIG),
        # `configs/models/qwen3-0.6b.yaml` is JSON-formatted despite its
        # extension, and the repository reads it with `json.loads` everywhere
        # else (`evaluation/fixtures.py`, `models/qwen3_reference.py`,
        # `export/onnx_matrix.py`, `backends/mlx_baseline.py`,
        # `quantization/parity.py`). Follow that convention rather than
        # accepting a YAML superset this contract's producers never emit.
        "model_contract": _load_json(repo_root / DEFAULT_MODEL_CONTRACT),
        "export_contract": _load_json(repo_root / DEFAULT_EXPORT_CONTRACT),
    }


def validate_repository(repo_root: Path) -> None:
    """Validate the committed calibration contract rooted at *repo_root*."""

    config_path = repo_root / DEFAULT_CALIBRATION_CONFIG
    if not config_path.is_file():
        raise CalibrationValidationError(
            f"calibration contract is missing: {config_path}"
        )
    inputs = load_inputs(repo_root)
    config = _load_yaml(config_path)
    if not isinstance(config, Mapping):
        raise CalibrationValidationError(
            f"calibration contract is not a YAML mapping: {config_path}"
        )
    validate_documents(config=config, **inputs)

    expected_text = render_document(
        build_document(
            bundle=inputs["bundle"],
            workload_config=inputs["workload_config"],
            model_contract=inputs["model_contract"],
            export_contract=inputs["export_contract"],
        )
    )
    if config_path.read_text(encoding="utf-8") != expected_text:
        raise CalibrationValidationError(
            "committed calibration contract is not byte-identical to a fresh "
            f"regeneration; run: {GENERATE_COMMAND}"
        )


def generate_repository(repo_root: Path) -> Path:
    """Regenerate the committed calibration contract and return its path."""

    inputs = load_inputs(repo_root)
    document = build_document(
        bundle=inputs["bundle"],
        workload_config=inputs["workload_config"],
        model_contract=inputs["model_contract"],
        export_contract=inputs["export_contract"],
    )
    config_path = repo_root / DEFAULT_CALIBRATION_CONFIG
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text(render_document(document), encoding="utf-8")
    return config_path


def fetch_dataset_metadata(dataset_id: str, *, timeout: float = 20.0) -> dict[str, Any]:
    """Fetch one Hugging Face dataset's revision and card licence.

    Only used by ``verify --online``. Never called from tests, which must stay
    offline and deterministic.
    """

    url = HF_DATASET_API.format(dataset_id=dataset_id)
    try:
        with urllib.request.urlopen(url, timeout=timeout) as response:  # noqa: S310
            payload = json.load(response)
    except (urllib.error.URLError, TimeoutError, ValueError) as exc:
        raise CalibrationValidationError(
            f"{dataset_id}: could not fetch {url}: {exc}"
        ) from exc
    return {
        "sha": payload.get("sha"),
        "license": (payload.get("cardData") or {}).get("license"),
    }


def verify_external_candidates_online(
    candidates: Iterable[Mapping[str, Any]] = EXTERNAL_CANDIDATES,
) -> None:
    """Re-fetch every tier-2 revision and licence and fail closed on drift."""

    for candidate in candidates:
        dataset_id = str(candidate["id"])
        upstream = fetch_dataset_metadata(dataset_id)
        _require(
            upstream["sha"] == candidate["revision"],
            f"{dataset_id}: upstream revision is {upstream['sha']}, "
            f"pinned revision is {candidate['revision']}",
        )
        _require(
            upstream["license"] == candidate["license"],
            f"{dataset_id}: upstream licence is {upstream['license']}, "
            f"pinned licence is {candidate['license']}",
        )


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse calibration CLI arguments."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path.cwd())
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser(
        "generate",
        help="rewrite configs/quantization/calibration.yaml from committed inputs",
    )
    verify = subparsers.add_parser(
        "verify",
        help="full offline validation; identical to `check` unless --online",
    )
    verify.add_argument(
        "--online",
        action="store_true",
        help=(
            "additionally re-fetch tier-2 dataset revisions and licences from "
            "the HF API; the only behaviour `check` cannot perform"
        ),
    )
    subparsers.add_parser(
        "check",
        help="full offline validation; identical to `verify` without --online, "
        "and the CI gate because it cannot reach the network",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Run the calibration corpus CLI."""

    args = parse_args(argv)
    repo_root = args.repo_root.resolve()
    try:
        if args.command == "generate":
            path = generate_repository(repo_root)
            print(f"wrote {path}")
        else:
            validate_repository(repo_root)
            if args.command == "verify" and args.online:
                verify_external_candidates_online()
    except (
        CalibrationValidationError,
        static_cache.CacheContractError,
        OSError,
    ) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"T40 calibration corpus {args.command} passed: {repo_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
