class ClassificationTests(unittest.TestCase):
    def test_bucket_invariant_holds_over_a_whole_document(self) -> None:
        text = (
            "The prefill graph has 8,753 nodes and 460 `Cast` nodes.\n"
            "It grows 1.32x. Section 5.4 covers 32,768 bytes of mask.\n"
            "Digest a61ed2ef. Model revision 28 layers. 99999999 unexplained.\n"
        )
        fixture = AuditFixture(text)
        buckets = fixture.buckets()
        self.assertEqual(
            sum(len(v) for v in buckets.values()), len(fixture.tokens))
        placed = [t for entries in buckets.values() for t, _ in entries]
        self.assertEqual(len(placed), len(set(id(t) for t in placed)))

    def test_a_literal_that_only_matches_the_baseline_moves(self) -> None:
        fixture = AuditFixture("prefill carries 8,753 nodes")
        self.assertEqual(fixture.bucket_of("8,753"), "MOVES")
        meaning = fixture.meanings_of("8,753")[0]
        self.assertEqual(meaning.baseline, 8753)
        self.assertEqual(meaning.current, 7634)
        self.assertTrue(meaning.needs_edit)

    def test_an_unchanged_value_is_static(self) -> None:
        # 341 prefill `Concat` nodes are unchanged by the re-export, and no
        # other measured value equals 341.
        fixture = AuditFixture("there are 341 `Concat` nodes")
        self.assertEqual(fixture.bucket_of("341"), "STATIC")

    def test_readings_that_share_a_fate_are_reported_but_not_ambiguous(
        self,
    ) -> None:
        # 254 is both the `MatMul` count and the external-initializer count,
        # in the fixtures and in the real graphs. Neither moves, so a reviewer
        # has one decision, not two -- but both readings are still carried.
        fixture = AuditFixture("there are 254 `MatMul` nodes")
        self.assertEqual(fixture.bucket_of("254"), "STATIC")
        keys = {m.key for m in fixture.meanings_of("254")}
        self.assertIn("count:op:*:*:MatMul", keys)
        self.assertIn("count:external_initializers:*:*", keys)

    def test_a_node_count_and_its_rule_population_move_together(self) -> None:
        # 8,753 is the node count and the node-count rule's own population.
        # Both move to 7,634, so this is MOVES rather than a false ambiguity.
        fixture = AuditFixture("prefill has 8,753 nodes")
        self.assertEqual(fixture.bucket_of("8,753"), "MOVES")
        self.assertGreater(len(fixture.meanings_of("8,753")), 1)

    def test_a_value_with_two_meanings_is_ambiguous(self) -> None:
        # 118 is prefill's ConstantOfShape count and decode's wide-IO count.
        fixture = AuditFixture("the count is 118")
        # The first moves to 62; the second does not move at all, so the
        # readings imply different actions.
        self.assertEqual(fixture.bucket_of("118"), "AMBIGUOUS")
        meanings = fixture.meanings_of("118")
        keys = {m.key for m in meanings}
        self.assertIn("count:op:*:*:ConstantOfShape", keys)
        self.assertIn("count:finding:*:*:R-WIDE-IO-BOUNDARY", keys)
        self.assertTrue(any(m.needs_edit for m in meanings))
        self.assertTrue(any(not m.needs_edit for m in meanings))

    def test_ambiguity_flags_whether_any_reading_moved(self) -> None:
        # 56 is the pre-promotion prefill `Pad` count and decode's
        # `ScatterElements` count; only the first moves.
        fixture = AuditFixture("56 appears twice")
        self.assertEqual(fixture.bucket_of("56"), "AMBIGUOUS")
        meanings = fixture.meanings_of("56")
        self.assertTrue(any(m.needs_edit for m in meanings))
        self.assertTrue(any(not m.needs_edit for m in meanings))

    def test_unexplained_numbers_are_unclassified(self) -> None:
        fixture = AuditFixture("an inline attribute of 26,706 bytes")
        self.assertEqual(fixture.bucket_of("26,706"), "UNCLASSIFIED")
        self.assertEqual(fixture.meanings_of("26,706"), [])

    def test_the_same_claim_at_four_contexts_is_one_meaning(self) -> None:
        # 460 `Cast` is measured at every variant. Without the collapse this
        # reads as several competing meanings and drowns the queue.
        fixture = AuditFixture("460 `Cast` nodes")
        self.assertEqual(fixture.bucket_of("460"), "STATIC")
        self.assertEqual(len(fixture.meanings_of("460")), 1)

    def test_a_superseded_digest_moves(self) -> None:
        fixture = AuditFixture("x")
        stale = fixture.pre_digest("S128", "prefill")
        fixture = AuditFixture(f"S128 prefill is `{stale}`")
        self.assertEqual(fixture.bucket_of(stale), "MOVES")

    def test_an_unchanged_decode_digest_is_static(self) -> None:
        fixture = AuditFixture("x")
        digest = fixture.post_digest("S128", "decode")
        fixture = AuditFixture(f"S128 decode is `{digest}`")
        self.assertEqual(fixture.bucket_of(digest), "STATIC")

    def test_a_denominator_that_only_appears_in_finding_prose_is_measured(
        self,
    ) -> None:
        fixture = AuditFixture("804 of 1,257 shape-defining inputs")
        self.assertEqual(fixture.bucket_of("1,257"), "MOVES")
        self.assertEqual(fixture.meanings_of("1,257")[0].current, 922)

    def test_a_ratio_is_matched_at_the_precision_written(self) -> None:
        # 2100000 / 1600000 = 1.3125 -> "1.31x"
        fixture = AuditFixture("the protobuf grows 1.31x from S128 to S512")
        self.assertIn(fixture.bucket_of("1.31x"), {"STATIC", "AMBIGUOUS"})
        keys = {m.key for m in fixture.meanings_of("1.31x")}
        self.assertTrue(any(k.startswith("ratio:onnx_bytes:") for k in keys))

    def test_a_percentage_is_matched_at_the_precision_written(self) -> None:
        # 254 MatMul of 7634 nodes = 3.3272...% -> "3.33%"
        fixture = AuditFixture("`MatMul` is 3.33% of the node list")
        keys = {m.key for m in fixture.meanings_of("3.33%")}
        self.assertIn("percent:op_share:*:*:MatMul", keys)

    def test_no_baseline_difference_means_no_moves(self) -> None:
        fixture = AuditFixture("prefill carries 8,753 nodes", post=False)
        self.assertEqual(fixture.buckets()["MOVES"], [])
        self.assertEqual(fixture.bucket_of("8,753"), "STATIC")


