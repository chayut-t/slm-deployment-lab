class EndToEndCliTests(unittest.TestCase):
    """Drive the CLI over a throwaway git repository."""

    def _repo(self, tmp: Path, doc_text: str) -> Path:
        root = tmp / "repo"
        root.mkdir()
        env_git = ["git", "-C", str(root)]
        subprocess.run(env_git + ["init", "-q"], check=True)
        subprocess.run(env_git + ["config", "user.email", "t@example.com"],
                       check=True)
        subprocess.run(env_git + ["config", "user.name", "T"], check=True)
        for relpath, text in evidence_files(**PRE).items():
            path = root / relpath
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        (root / "docs" / "results" / "onnx").mkdir(parents=True, exist_ok=True)
        (root / "docs" / "results" / "onnx" / "graph-inspection.md").write_text(
            doc_text, encoding="utf-8")
        subprocess.run(env_git + ["add", "-A"], check=True)
        subprocess.run(env_git + ["commit", "-qm", "pre"], check=True)
        return root

    def _run(self, argv: Sequence[str]) -> tuple:
        buffer = io.StringIO()
        with redirect_stdout(buffer):
            code = audit.main(list(argv))
        return code, buffer.getvalue()

    def setUp(self) -> None:
        self._saved_documents = audit.CLAIM_DOCUMENTS
        audit.CLAIM_DOCUMENTS = (
            ("docs/results/onnx/graph-inspection.md", "reconcile"),
        )
        # These fixtures are complete repositories in their own right, so the
        # machine's artifact store must not reach into them. Each test that
        # cares about the ambient variable sets it itself.
        patcher = mock.patch.dict(os.environ, {}, clear=False)
        patcher.start()
        os.environ.pop("SLM_LAB_ARTIFACT_ROOT", None)
        self.addCleanup(patcher.stop)

    def tearDown(self) -> None:
        audit.CLAIM_DOCUMENTS = self._saved_documents

    def test_citations_exits_zero_on_a_consistent_tree(self) -> None:
        text = (
            "| Variant | Graph | Nodes |\n"
            "|---|---|---:|\n"
            "| S128 | prefill | 8,753 |\n"
        )
        with TemporaryDirectory() as tmp:
            root = self._repo(Path(tmp), text)
            code, out = self._run(["citations", "--repo-root", str(root)])
        self.assertEqual(code, 0, out)
        self.assertIn("no disagreements", out)

    def test_an_ambient_artifact_root_does_not_reach_into_another_tree(
        self,
    ) -> None:
        # Regression: the tool used to read SLM_LAB_ARTIFACT_ROOT whatever it
        # had been pointed at, so a machine with the variable exported re-hashed
        # the real graphs and reported six conflicts against these fixtures.
        text = (
            "| Variant | Graph | Nodes |\n"
            "|---|---|---:|\n"
            "| S128 | prefill | 8,753 |\n"
        )
        with TemporaryDirectory() as tmp:
            root = self._repo(Path(tmp), text)
            store = Path(tmp) / "store"
            (store / "onnx" / "reference" / "T20" / "S128").mkdir(parents=True)
            (store / "onnx" / "reference" / "T20" / "S128"
             / "prefill.onnx").write_bytes(b"a different repository's graph")
            with mock.patch.dict(
                os.environ, {"SLM_LAB_ARTIFACT_ROOT": str(store)}
            ):
                code, out = self._run(["citations", "--repo-root", str(root)])
        self.assertEqual(code, 0, out)
        self.assertIn("no disagreements", out)
        self.assertIn("declined the ambient SLM_LAB_ARTIFACT_ROOT", out)

    def test_an_explicit_artifact_root_is_still_honoured(self) -> None:
        # The decline is about ambient configuration, not about re-hashing:
        # naming the path asserts that those bytes belong to these records.
        text = "nothing to bind here\n"
        with TemporaryDirectory() as tmp:
            root = self._repo(Path(tmp), text)
            store = Path(tmp) / "explicit"
            (store / "S128").mkdir(parents=True)
            (store / "S128" / "prefill.onnx").write_bytes(b"wrong bytes")
            code, out = self._run([
                "citations", "--repo-root", str(root),
                "--artifact-root", str(store),
            ])
        self.assertEqual(code, 1, out)
        self.assertIn("digest:graph:S128:prefill", out)

    def test_citations_exits_non_zero_after_the_evidence_moves(self) -> None:
        text = (
            "| Variant | Graph | Nodes |\n"
            "|---|---|---:|\n"
            "| S128 | prefill | 8,753 |\n"
        )
        with TemporaryDirectory() as tmp:
            root = self._repo(Path(tmp), text)
            for relpath, body in evidence_files(**POST).items():
                (root / relpath).write_text(body, encoding="utf-8")
            code, out = self._run(["citations", "--repo-root", str(root)])
        self.assertEqual(code, 1)
        self.assertIn("8,753", out)
        self.assertIn("What this does not prove", out)

    def test_claims_reports_moves_against_the_pre_promotion_commit(self) -> None:
        text = "The prefill graph carries 8,753 nodes.\n"
        with TemporaryDirectory() as tmp:
            root = self._repo(Path(tmp), text)
