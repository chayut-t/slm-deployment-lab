class DictReader(audit.Reader):
    """An in-memory snapshot of a repository."""

    def __init__(self, files: Dict[str, str], name: str = "fixture") -> None:
        self.files = {k: v.encode("utf-8") for k, v in files.items()}
        self.name = name

    def read_bytes(self, relpath: str) -> Optional[bytes]:
        return self.files.get(relpath)

    def paths(self) -> Sequence[str]:
        return sorted(self.files)


def _digest(seed: str) -> str:
    return hashlib.sha256(seed.encode("utf-8")).hexdigest()


