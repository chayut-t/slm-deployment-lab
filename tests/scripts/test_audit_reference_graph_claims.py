class TokenizerTests(unittest.TestCase):
    def tokens(self, text: str, digests: Sequence[str] = ()):
        return audit.tokenize("d.md", "reconcile", text, digests)

    def test_thousands_separators_are_one_token(self) -> None:
        tokens = self.tokens("the graph has 8,753 nodes")
        self.assertEqual([t.raw for t in tokens], ["8,753"])
        self.assertEqual(tokens[0].integral, 8753)

    def test_trailing_comma_is_not_part_of_the_number(self) -> None:
        tokens = self.tokens("largest=(32768, '/Constant_99')")
        self.assertEqual([t.raw for t in tokens], ["32768"])

    def test_percent_and_multiplier_forms(self) -> None:
        tokens = self.tokens("grows 22.6x and is 2.9% of the list")
        self.assertEqual(
            [(t.raw, t.form) for t in tokens],
            [("22.6x", "multiplier"), ("2.9%", "percent")],
        )

    def test_dotted_versions_are_one_token(self) -> None:
        tokens = self.tokens("python 3.11.15 and torch 2.7.1")
        self.assertEqual([t.raw for t in tokens], ["3.11.15", "2.7.1"])
        self.assertTrue(all(t.form == "dotted" for t in tokens))

    def test_digits_glued_to_an_identifier_are_not_numbers(self) -> None:
        # S128, float16, sha256 and T20 are identifiers, not claims.
        tokens = self.tokens("S128 float16 sha256 T20 int64 LEARN-10")
        self.assertEqual([t.raw for t in tokens], ["10"])

    def test_digest_needs_a_digit_and_a_letter_or_a_known_prefix(self) -> None:
        known = ["deadbeefdeadbeefdeadbeefdeadbeefdeadbeef" + "0" * 24]
        self.assertEqual(
            [t.raw for t in self.tokens("the word defaced is not a digest")],
            [],
        )
        tokens = self.tokens("digest a61ed2ef and deadbeefdead", known)
        self.assertEqual(
            sorted(t.raw for t in tokens), ["a61ed2ef", "deadbeefdead"])

    def test_truncated_digest_is_a_hex_token(self) -> None:
        tokens = self.tokens("quotes `a61ed2ef1e3f`")
        self.assertEqual([(t.raw, t.form) for t in tokens],
                         [("a61ed2ef1e3f", "hex")])

    def test_section_and_line_references_get_their_own_form(self) -> None:
        tokens = self.tokens("see section 5.4 and graph-inspection.md:725")
        self.assertEqual([(t.raw, t.form) for t in tokens],
                         [("5.4", "section-ref"), ("725", "line-ref")])

    def test_every_token_carries_file_and_line(self) -> None:
        tokens = self.tokens("first 12\nsecond 34\n")
        self.assertEqual([(t.where, t.raw) for t in tokens],
                         [("d.md:1", "12"), ("d.md:2", "34")])


