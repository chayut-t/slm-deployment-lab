        with TemporaryDirectory() as tmp:
            root = self._repo(Path(tmp), text)
            code, out = self._run(["claims", "--repo-root", str(root)])
        self.assertEqual(code, 0)
        self.assertIn("empty by construction", out)
        self.assertIn("UNCLASSIFIED", out)


