class CitationTests(unittest.TestCase):
    def snapshot(self, **overrides):
        params = dict(POST)
        params.update(overrides)
        return audit.harvest(DictReader(evidence_files(**params)))

    def test_a_table_digest_that_disagrees_is_a_mismatch(self) -> None:
        snap = self.snapshot()
        stale = _digest("pad-S128-prefill")
        text = (
            "| Variant | Graph | Graph SHA-256 |\n"
            "|---|---|---|\n"
            f"| S128 | `S128/prefill.onnx` | `{stale}` |\n"
        )
        findings = audit.check_table_citations("d.md", text, snap)
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0].severity, "mismatch")
        self.assertEqual(findings[0].where, "d.md:3")

    def test_a_table_digest_that_agrees_is_silent(self) -> None:
        snap = self.snapshot()
        good = _digest("concat-S128-prefill")
        text = (
            "| Variant | Graph | Graph SHA-256 |\n"
            "|---|---|---|\n"
            f"| S128 | `S128/prefill.onnx` | `{good}` |\n"
        )
        self.assertEqual(audit.check_table_citations("d.md", text, snap), [])

    def test_a_table_node_count_that_disagrees_is_a_mismatch(self) -> None:
        snap = self.snapshot()
        text = (
            "| Variant | Graph | Nodes | `.onnx` bytes |\n"
            "|---|---:|---:|---:|\n"
            "| S128 | prefill | 8,753 | 1,600,000 |\n"
        )
        findings = audit.check_table_citations("d.md", text, snap)
        self.assertEqual([f.severity for f in findings], ["mismatch"])
        self.assertIn("8,753", findings[0].detail)

    def test_a_table_row_that_agrees_is_silent(self) -> None:
        snap = self.snapshot()
        text = (
            "| Variant | Graph | Nodes | `.onnx` bytes |\n"
            "|---|---:|---:|---:|\n"
            "| S128 | prefill | 7,634 | 1,600,000 |\n"
        )
        self.assertEqual(audit.check_table_citations("d.md", text, snap), [])

    def test_an_annotated_cell_passes_when_one_number_is_measured(self) -> None:
        snap = self.snapshot()
        text = (
            "| Rule | Prefill count | Decode count |\n"
            "|---|---:|---:|\n"
            "| `R-WIDE-IO-BOUNDARY` | 58 | 118 |\n"
        )
        self.assertEqual(audit.check_table_citations("d.md", text, snap), [])

    def test_an_operator_span_that_disagrees_is_a_mismatch(self) -> None:
        snap = self.snapshot()
        findings = audit.check_operator_citations(
            "d.md", "the histogram shows `Cast=999`", snap)
        self.assertEqual([f.severity for f in findings], ["mismatch"])

    def test_an_operator_span_binds_the_kind_only_when_it_qualifies(
        self,
    ) -> None:
        snap = self.snapshot()
        # 459 is decode's Shape count. The trailing "prefill's 121" must not
        # bind this span to prefill.
        clean = ("it carries 459 `Shape` nodes against prefill's 121")
        self.assertEqual(audit.check_operator_citations("d.md", clean, snap), [])
        # An immediate qualifier does bind, and then the wrong kind fails.
        findings = audit.check_operator_citations(
            "d.md", "in prefill `Shape=459`", snap)
        self.assertEqual([f.severity for f in findings], ["mismatch"])

    def test_disagreeing_generated_sources_are_reported(self) -> None:
        files = evidence_files(**POST)
        manifest = json.loads(files["results/manifests/onnx/S128.json"])
        manifest["artifacts"]["prefill"]["sha256"] = _digest("something-else")
        files["results/manifests/onnx/S128.json"] = json.dumps(manifest)
        snap = audit.harvest(DictReader(files))
        findings = audit.check_evidence_conflicts(snap)
        identities = {f.where for f in findings}
        self.assertIn("digest:graph:S128:prefill", identities)
        self.assertTrue(all(f.severity == "conflict" for f in findings))

    def test_a_coherent_evidence_set_has_no_conflicts(self) -> None:
        self.assertEqual(audit.check_evidence_conflicts(self.snapshot()), [])

    def test_an_unresolved_digest_is_reported(self) -> None:
        snap = self.snapshot()
        classifier = audit.Classifier(snap, snap)
        known = classifier.known_digests()
        text = "the digest is `0123456789abcdef0123456789abcdef`"
        tokens = audit.tokenize("d.md", "reconcile", text, known)
        findings = audit.check_unresolved_digests("d.md", tokens, known)
        self.assertEqual([f.severity for f in findings], ["unresolved"])

    def test_a_known_digest_is_not_reported_as_unresolved(self) -> None:
        snap = self.snapshot()
        classifier = audit.Classifier(snap, snap)
        known = classifier.known_digests()
        text = f"the digest is `{_digest('concat-S128-prefill')}`"
        tokens = audit.tokenize("d.md", "reconcile", text, known)
        self.assertEqual(
            audit.check_unresolved_digests("d.md", tokens, known), [])

    def test_an_inline_digest_beside_its_graph_is_checked(self) -> None:
        snap = self.snapshot()
        stale = _digest("pad-S128-prefill")
        line = f"`S128/prefill.onnx` still reads `{stale}` today"
        findings = audit.check_inline_digest_citations("d.md", line, snap)
        self.assertEqual([f.severity for f in findings], ["mismatch"])


class ArtifactRehashTests(unittest.TestCase):
    def test_a_missing_artifact_root_degrades_cleanly(self) -> None:
        snap = audit.harvest(
            DictReader(evidence_files(**POST)),
            artifact_root=Path("/nonexistent/artifact/root"),
        )
        self.assertTrue(
            any("not present" in note for note in snap.notes), snap.notes)
        self.assertEqual(audit.check_evidence_conflicts(snap), [])

    def test_bytes_on_disk_are_compared_against_the_records(self) -> None:
        with TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "S128").mkdir()
            (root / "S128" / "prefill.onnx").write_bytes(b"not the graph")
            (root / "S128" / "decode.onnx").write_bytes(b"nor this")
            snap = audit.harvest(
                DictReader(evidence_files(**POST)), artifact_root=root)
            conflicts = {f.where for f in audit.check_evidence_conflicts(snap)}
            self.assertIn("digest:graph:S128:prefill", conflicts)
            self.assertIn("bytes:onnx:S128:prefill", conflicts)
            # S512 has no bytes on disk, so nothing is asserted about it.
            self.assertNotIn("digest:graph:S512:prefill", conflicts)

    def test_matching_bytes_produce_no_conflict(self) -> None:
        with TemporaryDirectory() as tmp:
            root = Path(tmp)
            files = evidence_files(**POST)
            payload = b"the real graph bytes"
            digest = hashlib.sha256(payload).hexdigest()
            manifest = json.loads(files["results/manifests/onnx/S128.json"])
            manifest["artifacts"]["prefill"]["sha256"] = digest
            manifest["artifacts"]["prefill"]["size_bytes"] = len(payload)
            files["results/manifests/onnx/S128.json"] = json.dumps(manifest)
            config = json.loads(
                files["configs/models/qwen3-0.6b-onnx-export.json"])
            config["evidence_attestation"]["graph_sha256"]["S128"]["prefill"] = \
                digest
            files["configs/models/qwen3-0.6b-onnx-export.json"] = json.dumps(
                config)
            report = json.loads(files["results/graph/S128.json"])
            report["graphs"]["prefill"]["source_sha256"] = digest
            files["results/graph/S128.json"] = json.dumps(report)
            parity = json.loads(files["results/graph/parity/S128-ort-cpu.json"])
            parity["graph_digests"]["prefill"]["sha256"] = digest
            files["results/graph/parity/S128-ort-cpu.json"] = json.dumps(parity)
            (root / "S128").mkdir()
            (root / "S128" / "prefill.onnx").write_bytes(payload)
            snap = audit.harvest(DictReader(files), artifact_root=root)
            conflicts = {f.where for f in audit.check_evidence_conflicts(snap)}
            self.assertNotIn("digest:graph:S128:prefill", conflicts)
            self.assertNotIn("bytes:onnx:S128:prefill", conflicts)


class ArtifactRootResolutionTests(unittest.TestCase):
    """Which artifact tree the CLI agrees to re-hash.

    ``SLM_LAB_ARTIFACT_ROOT`` is ambient machine configuration. Honouring it
    while auditing some *other* repository root hashes one tree's graphs
    against another tree's records, which reports every digest as a conflict.
    """

    def resolve(self, repo_root: Path, override=None, env=None):
        environ = {} if env is None else {"SLM_LAB_ARTIFACT_ROOT": env}
        with mock.patch.dict(os.environ, environ, clear=True):
            return audit._resolve_artifact_root(repo_root, override)

    def test_no_ambient_variable_and_no_override_means_no_rehash(self) -> None:
        self.assertEqual(self.resolve(REPO_ROOT), (None, None))

    def test_the_ambient_variable_is_used_for_this_checkout(self) -> None:
        root, declined = self.resolve(REPO_ROOT, env="/store")
        self.assertEqual(root, Path("/store/onnx/reference/T20"))
        self.assertIsNone(declined)

    def test_the_ambient_variable_is_declined_for_another_root(self) -> None:
        root, declined = self.resolve(Path("/somewhere/else"), env="/store")
        self.assertIsNone(root)
        self.assertIn("SLM_LAB_ARTIFACT_ROOT", declined or "")
        self.assertIn("/somewhere/else", declined or "")

    def test_an_explicit_override_wins_over_the_ambient_variable(self) -> None:
        root, declined = self.resolve(
            Path("/somewhere/else"), override="/explicit", env="/store")
        self.assertEqual(root, Path("/explicit"))
        self.assertIsNone(declined)


