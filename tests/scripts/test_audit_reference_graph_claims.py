def document(text: str) -> Dict[str, str]:
    return {"docs/results/onnx/graph-inspection.md": text}


class AuditFixture:
    """A pre/post pair of evidence snapshots plus a document under review."""

    def __init__(self, doc_text: str, post: bool = True) -> None:
        pre_files = evidence_files(**PRE)
        post_files = evidence_files(**POST)
        current_files = dict(post_files if post else pre_files)
        current_files.update(document(doc_text))
        self.doc_path = "docs/results/onnx/graph-inspection.md"
        self.doc_text = doc_text
        self.current = audit.harvest(DictReader(current_files, "current"))
        self.baseline = audit.harvest(DictReader(pre_files, "baseline"))
        self.classifier = audit.Classifier(self.current, self.baseline)
        self.tokens = audit.tokenize(
            self.doc_path, "reconcile", doc_text,
            self.classifier.known_digests(),
        )

    def buckets(self) -> Dict[str, List]:
        out: Dict[str, List] = {
            "MOVES": [], "STATIC": [], "AMBIGUOUS": [], "UNCLASSIFIED": []}
        for token in self.tokens:
            bucket, meanings = self.classifier.classify(token)
            out[bucket].append((token, meanings))
        return out

    def bucket_of(self, literal: str) -> str:
        for token in self.tokens:
            if token.raw == literal:
                return self.classifier.classify(token)[0]
        raise AssertionError(f"literal {literal!r} was never tokenized")

    def meanings_of(self, literal: str):
        for token in self.tokens:
            if token.raw == literal:
                return self.classifier.classify(token)[1]
        raise AssertionError(f"literal {literal!r} was never tokenized")

    def pre_digest(self, variant: str, kind: str) -> str:
        return _digest(f"pad-{variant}-{kind}") if kind == "prefill" \
            else _digest(f"decode-{variant}")

    def post_digest(self, variant: str, kind: str) -> str:
        return _digest(f"concat-{variant}-{kind}") if kind == "prefill" \
            else _digest(f"decode-{variant}")


