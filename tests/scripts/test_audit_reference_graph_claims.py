def _load_tool():
    spec = importlib.util.spec_from_file_location("audit_tool", TOOL_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import {TOOL_PATH}")
    module = importlib.util.module_from_spec(spec)
    # Registered before execution so `dataclasses` can resolve the module's own
    # annotations on Python 3.9.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


